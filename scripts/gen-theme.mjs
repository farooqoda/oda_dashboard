const v = (fam, shade) => `--c-${fam}${shade === 'DEFAULT' ? '' : '-' + shade}`;
let light = '', dark = '';
for (const [fam, { light: L, dark: D }] of Object.entries(CUSTOM)) {
  for (const s of Object.keys(L)) {
    light += `  ${v(fam, s)}: ${hex2rgb(L[s])};\n`;
    dark += `  ${v(fam, s)}: ${hex2rgb(D[s])};\n`;
  }
}
for (const fam of FAMILIES) {
  for (const s of SHADES) {
    light += `  ${v(fam, s)}: ${hex2rgb(colors[fam][s])};\n`;
    dark += `  ${v(fam, s)}: ${hex2rgb(colors[fam][MIRROR[s]])};\n`;
  }
}
const css = `/* Generated by scripts/gen-theme.mjs — do not edit by hand. */
:root, .keep-light {
${light}}
html.dark {
${dark}}
/* parts that keep their light-theme look: LinkedIn's own profile layout, the dark "accent" tiles, photo cards */
html.dark .keep-light, html.dark .tile-dark {
${light}}
`;
writeFileSync(new URL('../src/theme.css', import.meta.url), css);
